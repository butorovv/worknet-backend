BEGIN;

CREATE TABLE uploaded_resumes (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    original_filename     text NOT NULL,
    content_type          text NOT NULL,
    file_size             bigint NOT NULL,
    storage_key           text NOT NULL,
    status                text NOT NULL DEFAULT 'uploaded',
    parser_version        text,

    uploaded_at           timestamptz NOT NULL DEFAULT now(),
    parsed_at             timestamptz,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    deleted_at            timestamptz,

    CONSTRAINT uq_uploaded_resumes_id_user UNIQUE (id, user_id),
    CONSTRAINT ck_uploaded_resumes_filename_not_empty CHECK (
        length(trim(original_filename)) > 0
    ),
    CONSTRAINT ck_uploaded_resumes_content_type CHECK (
        content_type IN (
            'application/pdf',
            'application/msword',
            'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
        )
    ),
    CONSTRAINT ck_uploaded_resumes_file_size CHECK (
        file_size > 0
    ),
    CONSTRAINT ck_uploaded_resumes_storage_key_not_empty CHECK (
        length(trim(storage_key)) > 0
    ),
    CONSTRAINT ck_uploaded_resumes_status CHECK (
        status IN ('uploaded', 'processing', 'parsed', 'failed', 'applied', 'archived')
    )
);

CREATE UNIQUE INDEX ux_uploaded_resumes_storage_key
    ON uploaded_resumes (storage_key);

CREATE INDEX idx_uploaded_resumes_user_status
    ON uploaded_resumes (user_id, status, uploaded_at DESC)
    WHERE deleted_at IS NULL;


CREATE TABLE parsed_resume_drafts (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    resume_id             bigint NOT NULL,
    user_id               bigint NOT NULL,
    applied_profile_id    bigint REFERENCES profiles(id) ON DELETE SET NULL,

    raw_ai_result         jsonb NOT NULL,
    normalized_preview    jsonb NOT NULL DEFAULT '{}'::jsonb,

    status                text NOT NULL DEFAULT 'pending',
    confidence_score      numeric(5,4),
    parser_version        text,
    error_message         text,

    applied_at            timestamptz,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_parsed_resume_drafts_resume_user
        FOREIGN KEY (resume_id, user_id)
        REFERENCES uploaded_resumes(id, user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_parsed_resume_drafts_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_parsed_resume_drafts_status CHECK (
        status IN ('pending', 'applied', 'rejected', 'expired', 'failed')
    ),
    CONSTRAINT ck_parsed_resume_drafts_confidence CHECK (
        confidence_score IS NULL OR (confidence_score >= 0 AND confidence_score <= 1)
    ),
    CONSTRAINT ck_parsed_resume_drafts_applied CHECK (
        status <> 'applied'
        OR
        (applied_profile_id IS NOT NULL AND applied_at IS NOT NULL)
    )
);

CREATE INDEX idx_parsed_resume_drafts_user_status
    ON parsed_resume_drafts (user_id, status, created_at DESC);

CREATE INDEX idx_parsed_resume_drafts_resume
    ON parsed_resume_drafts (resume_id);

CREATE UNIQUE INDEX ux_parsed_resume_drafts_pending_per_resume
    ON parsed_resume_drafts (resume_id)
    WHERE status = 'pending';

COMMIT;
