BEGIN;

CREATE TABLE profiles (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,

    full_name               text NOT NULL,
    headline                text,
    bio                     text,
    organization            text,
    location                text,
    avatar_url              text,

    status                  text NOT NULL DEFAULT 'draft',
    visibility              text NOT NULL DEFAULT 'public',
    open_to_collaboration   boolean NOT NULL DEFAULT false,

    contact_email           text,
    contact_visibility      text NOT NULL DEFAULT 'contacts',

    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    deleted_at              timestamptz,

    CONSTRAINT ck_profiles_full_name_not_empty CHECK (
        length(trim(full_name)) > 1
    ),
    CONSTRAINT ck_profiles_status CHECK (
        status IN ('draft', 'published', 'archived')
    ),
    CONSTRAINT ck_profiles_visibility CHECK (
        visibility IN ('public', 'registered', 'contacts', 'private')
    ),
    CONSTRAINT ck_profiles_contact_visibility CHECK (
        contact_visibility IN ('public', 'registered', 'contacts', 'private')
    ),
    CONSTRAINT ck_profiles_contact_email_format CHECK (
        contact_email IS NULL OR position('@' in contact_email) > 1
    )
);

CREATE INDEX idx_profiles_user_id
    ON profiles (user_id);

CREATE INDEX idx_profiles_status_visibility
    ON profiles (status, visibility)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_profiles_full_name_trgm
    ON profiles USING gin (full_name gin_trgm_ops)
    WHERE deleted_at IS NULL;


CREATE TABLE profile_links (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id      bigint NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,

    type            text NOT NULL,
    title           text,
    url             text NOT NULL,
    visibility      text NOT NULL DEFAULT 'public',
    position        integer NOT NULL DEFAULT 0,

    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_profile_links_type CHECK (
        type IN ('github', 'linkedin', 'telegram', 'portfolio', 'website', 'figma', 'notion', 'other')
    ),
    CONSTRAINT ck_profile_links_visibility CHECK (
        visibility IN ('public', 'registered', 'contacts', 'private')
    ),
    CONSTRAINT ck_profile_links_url_not_empty CHECK (
        length(trim(url)) > 0
    ),
    CONSTRAINT ck_profile_links_position CHECK (
        position >= 0
    )
);

CREATE UNIQUE INDEX ux_profile_links_profile_url
    ON profile_links (profile_id, lower(url));

CREATE INDEX idx_profile_links_profile_position
    ON profile_links (profile_id, position);

COMMIT;
