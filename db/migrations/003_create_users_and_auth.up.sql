BEGIN;

CREATE TABLE users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            text NOT NULL,
    email               text NOT NULL,
    status              text NOT NULL DEFAULT 'active',

    email_verified_at   timestamptz,
    last_seen_at        timestamptz,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz,

    CONSTRAINT ck_users_username_format CHECK (
        username ~ '^[a-zA-Z0-9_][a-zA-Z0-9_.-]{2,29}$'
    ),
    CONSTRAINT ck_users_email_format CHECK (
        position('@' in email) > 1
    ),
    CONSTRAINT ck_users_status CHECK (
        status IN ('active', 'blocked', 'deleted')
    )
);

CREATE UNIQUE INDEX ux_users_username_active
    ON users (lower(username))
    WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX ux_users_email_active
    ON users (lower(email))
    WHERE deleted_at IS NULL;

CREATE INDEX idx_users_status
    ON users (status)
    WHERE deleted_at IS NULL;


CREATE TABLE auth_identities (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    provider            text NOT NULL,
    provider_user_id    text,
    password_hash       text,

    last_used_at        timestamptz,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_auth_identities_provider CHECK (
        provider IN ('password', 'github', 'google')
    ),
    CONSTRAINT ck_auth_identities_payload CHECK (
        (provider = 'password' AND password_hash IS NOT NULL)
        OR
        (provider <> 'password' AND provider_user_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX ux_auth_identities_user_provider
    ON auth_identities (user_id, provider);

CREATE UNIQUE INDEX ux_auth_identities_provider_subject
    ON auth_identities (provider, provider_user_id)
    WHERE provider_user_id IS NOT NULL;

CREATE INDEX idx_auth_identities_user_id
    ON auth_identities (user_id);

COMMIT;
