BEGIN;

CREATE TABLE requests (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    space_id              bigint REFERENCES spaces(id) ON DELETE SET NULL,
    owner_id              bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,

    type                  text NOT NULL,
    status                text NOT NULL DEFAULT 'draft',
    visibility            text NOT NULL DEFAULT 'public',

    title                 text NOT NULL,
    description           text NOT NULL,
    expected_commitment   text,
    format                text NOT NULL DEFAULT 'portfolio',

    responses_count       integer NOT NULL DEFAULT 0,

    published_at          timestamptz,
    closed_at             timestamptz,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    deleted_at            timestamptz,

    CONSTRAINT ck_requests_type CHECK (
        type IN (
            'looking_for_contributor',
            'looking_for_feedback',
            'looking_for_coauthor',
            'looking_for_reviewer',
            'looking_for_teammate',
            'offering_help',
            'other'
        )
    ),
    CONSTRAINT ck_requests_status CHECK (
        status IN ('draft', 'open', 'closed', 'archived')
    ),
    CONSTRAINT ck_requests_visibility CHECK (
        visibility IN ('public', 'registered', 'members', 'private')
    ),
    CONSTRAINT ck_requests_format CHECK (
        format IN ('portfolio', 'paid', 'coauthorship', 'feedback', 'research', 'learning', 'equity', 'open_collaboration', 'other')
    ),
    CONSTRAINT ck_requests_title_not_empty CHECK (
        length(trim(title)) > 2
    ),
    CONSTRAINT ck_requests_description_not_empty CHECK (
        length(trim(description)) > 5
    ),
    CONSTRAINT ck_requests_responses_count CHECK (
        responses_count >= 0
    ),
    CONSTRAINT ck_requests_dates CHECK (
        published_at IS NULL
        OR closed_at IS NULL
        OR published_at <= closed_at
    )
);

CREATE INDEX idx_requests_owner_status_created
    ON requests (owner_id, status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_requests_space_status_created
    ON requests (space_id, status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_requests_status_published
    ON requests (status, published_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_requests_title_trgm
    ON requests USING gin (title gin_trgm_ops)
    WHERE deleted_at IS NULL;


CREATE TABLE request_skills (
    request_id    bigint NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
    skill_id      bigint NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,

    required      boolean NOT NULL DEFAULT true,
    priority      smallint NOT NULL DEFAULT 0,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (request_id, skill_id)
);

CREATE INDEX idx_request_skills_skill_request
    ON request_skills (skill_id, request_id);


CREATE TABLE request_responses (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    request_id             bigint NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
    respondent_id          bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,

    status                text NOT NULL DEFAULT 'pending',

    message               text NOT NULL,
    relevant_experience   text,
    desired_role          text,

    decided_by_user_id    bigint REFERENCES users(id) ON DELETE SET NULL,
    decided_at            timestamptz,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_request_responses_status CHECK (
        status IN ('pending', 'accepted', 'rejected', 'withdrawn')
    ),
    CONSTRAINT ck_request_responses_message_not_empty CHECK (
        length(trim(message)) > 0
    ),
    CONSTRAINT ck_request_responses_decision CHECK (
        status NOT IN ('accepted', 'rejected')
        OR
        (decided_by_user_id IS NOT NULL AND decided_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX ux_request_responses_request_user
    ON request_responses (request_id, respondent_id);

CREATE INDEX idx_request_responses_request_status_created
    ON request_responses (request_id, status, created_at DESC);

CREATE INDEX idx_request_responses_respondent_status_created
    ON request_responses (respondent_id, status, created_at DESC);

COMMIT;
