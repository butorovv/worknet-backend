BEGIN;

CREATE TABLE artifacts (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,

    type                text NOT NULL,
    title               text NOT NULL,
    description         text,

    url                 text,
    storage_key         text,
    provider_ref        text,

    visibility          text NOT NULL DEFAULT 'public',
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz,

    CONSTRAINT ck_artifacts_type CHECK (
        type IN ('github', 'notion', 'google_docs', 'figma', 'link', 'file', 'resume', 'other')
    ),
    CONSTRAINT ck_artifacts_visibility CHECK (
        visibility IN ('public', 'registered', 'contacts', 'members', 'private')
    ),
    CONSTRAINT ck_artifacts_title_not_empty CHECK (
        length(trim(title)) > 0
    ),
    CONSTRAINT ck_artifacts_location CHECK (
        url IS NOT NULL OR storage_key IS NOT NULL OR provider_ref IS NOT NULL
    )
);

CREATE INDEX idx_artifacts_owner_type_created
    ON artifacts (owner_id, type, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_artifacts_type_created
    ON artifacts (type, created_at DESC)
    WHERE deleted_at IS NULL;


CREATE TABLE contributions (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id               bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    space_id              bigint NOT NULL REFERENCES spaces(id) ON DELETE RESTRICT,
    request_id            bigint REFERENCES requests(id) ON DELETE SET NULL,

    title                 text NOT NULL,
    description           text,
    role_title            text,

    status                text NOT NULL DEFAULT 'pending',
    visibility            text NOT NULL DEFAULT 'public',

    confirmed_by_user_id  bigint REFERENCES users(id) ON DELETE SET NULL,
    confirmed_at          timestamptz,

    date_from             date,
    date_to               date,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    deleted_at            timestamptz,

    CONSTRAINT ck_contributions_title_not_empty CHECK (
        length(trim(title)) > 2
    ),
    CONSTRAINT ck_contributions_status CHECK (
        status IN ('pending', 'confirmed', 'rejected', 'revoked')
    ),
    CONSTRAINT ck_contributions_visibility CHECK (
        visibility IN ('public', 'registered', 'contacts', 'members', 'private')
    ),
    CONSTRAINT ck_contributions_confirmed CHECK (
        status <> 'confirmed'
        OR
        (confirmed_by_user_id IS NOT NULL AND confirmed_at IS NOT NULL)
    ),
    CONSTRAINT ck_contributions_dates CHECK (
        date_from IS NULL OR date_to IS NULL OR date_from <= date_to
    )
);

CREATE INDEX idx_contributions_user_status_created
    ON contributions (user_id, status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_contributions_space_status_created
    ON contributions (space_id, status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_contributions_request_id
    ON contributions (request_id)
    WHERE request_id IS NOT NULL AND deleted_at IS NULL;


CREATE TABLE profile_artifacts (
    profile_id    bigint NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    artifact_id   bigint NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,

    position      integer NOT NULL DEFAULT 0,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (profile_id, artifact_id),

    CONSTRAINT ck_profile_artifacts_position CHECK (
        position >= 0
    )
);

CREATE INDEX idx_profile_artifacts_artifact
    ON profile_artifacts (artifact_id);


CREATE TABLE space_artifacts (
    space_id      bigint NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
    artifact_id   bigint NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,

    position      integer NOT NULL DEFAULT 0,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (space_id, artifact_id),

    CONSTRAINT ck_space_artifacts_position CHECK (
        position >= 0
    )
);

CREATE INDEX idx_space_artifacts_artifact
    ON space_artifacts (artifact_id);


CREATE TABLE contribution_artifacts (
    contribution_id  bigint NOT NULL REFERENCES contributions(id) ON DELETE CASCADE,
    artifact_id      bigint NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,

    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (contribution_id, artifact_id)
);

CREATE INDEX idx_contribution_artifacts_artifact
    ON contribution_artifacts (artifact_id);


CREATE TABLE request_response_artifacts (
    response_id   bigint NOT NULL REFERENCES request_responses(id) ON DELETE CASCADE,
    artifact_id   bigint NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (response_id, artifact_id)
);

CREATE INDEX idx_request_response_artifacts_artifact
    ON request_response_artifacts (artifact_id);

COMMIT;
