BEGIN;

CREATE TABLE notifications (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id       bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    actor_id      bigint REFERENCES users(id) ON DELETE SET NULL,

    type          text NOT NULL,
    title         text NOT NULL,
    body          text,
    link_url      text,

    is_read       boolean NOT NULL DEFAULT false,
    read_at       timestamptz,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    deleted_at    timestamptz,

    CONSTRAINT ck_notifications_type_not_empty CHECK (
        length(trim(type)) > 0
    ),
    CONSTRAINT ck_notifications_title_not_empty CHECK (
        length(trim(title)) > 0
    ),
    CONSTRAINT ck_notifications_read_state CHECK (
        is_read = false OR read_at IS NOT NULL
    )
);

CREATE INDEX idx_notifications_user_created
    ON notifications (user_id, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_notifications_user_unread
    ON notifications (user_id, created_at DESC)
    WHERE is_read = false AND deleted_at IS NULL;

CREATE INDEX idx_notifications_actor_created
    ON notifications (actor_id, created_at DESC)
    WHERE actor_id IS NOT NULL AND deleted_at IS NULL;

COMMIT;
