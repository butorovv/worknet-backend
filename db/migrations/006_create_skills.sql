BEGIN;

CREATE TABLE skills (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name          text NOT NULL,
    slug          text NOT NULL,
    category      text,
    is_verified   boolean NOT NULL DEFAULT false,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_skills_slug UNIQUE (slug),
    CONSTRAINT ck_skills_name_not_empty CHECK (
        length(trim(name)) > 0
    ),
    CONSTRAINT ck_skills_slug_format CHECK (
        slug ~ '^[a-z0-9][a-z0-9-]{1,63}$'
    )
);

CREATE UNIQUE INDEX ux_skills_name_lower
    ON skills (lower(name));

CREATE INDEX idx_skills_category
    ON skills (category);


CREATE TABLE user_skills (
    user_id       bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    skill_id      bigint NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,

    level         text,
    source        text NOT NULL DEFAULT 'manual',
    years         numeric(4,1),
    is_primary    boolean NOT NULL DEFAULT false,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (user_id, skill_id),

    CONSTRAINT ck_user_skills_level CHECK (
        level IS NULL OR level IN ('beginner', 'junior', 'middle', 'senior', 'expert')
    ),
    CONSTRAINT ck_user_skills_source CHECK (
        source IN ('manual', 'resume', 'contribution')
    ),
    CONSTRAINT ck_user_skills_years CHECK (
        years IS NULL OR (years >= 0 AND years <= 80)
    )
);

CREATE INDEX idx_user_skills_skill_user
    ON user_skills (skill_id, user_id);

CREATE INDEX idx_user_skills_user_primary
    ON user_skills (user_id, is_primary DESC);

COMMIT;
