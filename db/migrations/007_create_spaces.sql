BEGIN;

CREATE TABLE spaces (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,

    slug                text NOT NULL,
    name                text NOT NULL,
    type                text NOT NULL DEFAULT 'other',
    status              text NOT NULL DEFAULT 'draft',
    visibility          text NOT NULL DEFAULT 'public',

    short_description   text,
    description         text,
    cover_url           text,

    strength_score      smallint NOT NULL DEFAULT 0,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    archived_at         timestamptz,
    deleted_at          timestamptz,

    CONSTRAINT ck_spaces_slug_format CHECK (
        slug ~ '^[a-z0-9][a-z0-9-]{2,80}$'
    ),
    CONSTRAINT ck_spaces_name_not_empty CHECK (
        length(trim(name)) > 1
    ),
    CONSTRAINT ck_spaces_type CHECK (
        type IN ('startup', 'study_project', 'research', 'hackathon', 'community', 'course', 'book', 'other')
    ),
    CONSTRAINT ck_spaces_status CHECK (
        status IN ('draft', 'active', 'in_review', 'archived')
    ),
    CONSTRAINT ck_spaces_visibility CHECK (
        visibility IN ('public', 'registered', 'members', 'private')
    ),
    CONSTRAINT ck_spaces_strength_score CHECK (
        strength_score >= 0 AND strength_score <= 100
    )
);

CREATE UNIQUE INDEX ux_spaces_slug_active
    ON spaces (lower(slug))
    WHERE deleted_at IS NULL;

CREATE INDEX idx_spaces_owner_status
    ON spaces (owner_id, status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_spaces_status_created
    ON spaces (status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_spaces_name_trgm
    ON spaces USING gin (name gin_trgm_ops)
    WHERE deleted_at IS NULL;


CREATE TABLE space_members (
    space_id            bigint NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
    user_id             bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    role                text NOT NULL DEFAULT 'contributor',
    status              text NOT NULL DEFAULT 'active',
    invited_by_user_id  bigint REFERENCES users(id) ON DELETE SET NULL,

    joined_at           timestamptz,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (space_id, user_id),

    CONSTRAINT ck_space_members_role CHECK (
        role IN ('owner', 'admin', 'contributor', 'viewer')
    ),
    CONSTRAINT ck_space_members_status CHECK (
        status IN ('invited', 'active', 'left', 'removed')
    )
);

CREATE UNIQUE INDEX ux_space_members_one_active_owner
    ON space_members (space_id)
    WHERE role = 'owner' AND status = 'active';

CREATE INDEX idx_space_members_user_status
    ON space_members (user_id, status);

CREATE INDEX idx_space_members_space_role_status
    ON space_members (space_id, role, status);


CREATE TABLE space_skills (
    space_id      bigint NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
    skill_id      bigint NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,

    priority      smallint NOT NULL DEFAULT 0,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (space_id, skill_id)
);

CREATE INDEX idx_space_skills_skill_space
    ON space_skills (skill_id, space_id);

COMMIT;
